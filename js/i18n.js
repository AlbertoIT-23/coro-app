let lang = 'it';

export const getLang = () => lang;

export function setLang(next) {
  if (strings[next]) lang = next;
}

export function detectLang(saved, browserLanguage = '') {
  if (strings[saved]) return saved;
  return browserLanguage.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function t(key, params = {}) {
  const text = strings[lang][key] ?? strings.it[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
}

export function translatePage(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}

export const missingKeys = () => {
  const it = Object.keys(strings.it);
  const en = Object.keys(strings.en);
  return { inEnglish: it.filter((k) => !strings.en[k]), inItalian: en.filter((k) => !strings.it[k]) };
};
